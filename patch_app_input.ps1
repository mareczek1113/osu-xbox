Patch "$app\MainPage.xaml.cs" {
  param($raw, $nl)
  if ($raw.Contains('setTextInput')) { return $raw }
  $L = { param([string[]]$l) ($l -join $nl) }

  # usings
  $raw = Rep $raw 'using Windows.Storage;' (& $L @('using Windows.Storage;', 'using Windows.System;', 'using Windows.UI.Text.Core;', 'using Windows.UI.ViewManagement;'))

  # suspend/resume logging, DPI and composition scale changes
  $raw = Rep $raw (& $L @(
'        Windows.UI.Xaml.Application.Current.Suspending += (_, _) => bridge.NotifySuspending();',
'        Windows.UI.Xaml.Application.Current.Resuming += (_, _) => bridge.NotifyResumed();')) (& $L @(
'        Windows.UI.Xaml.Application.Current.Suspending += (_, _) =>',
'        {',
'            log("suspending");',
'            bridge.NotifySuspending();',
'            log("suspend handled");',
'        };',
'',
'        Windows.UI.Xaml.Application.Current.Resuming += (_, _) =>',
'        {',
'            bridge.NotifyResumed();',
'            log("resumed");',
'        };',
'',
'        // The scale can change without the panel being resized (display mode or TV resolution changes).',
'        DisplayInformation.GetForCurrentView().DpiChanged += (_, _) => publishSize();',
'        Panel.CompositionScaleChanged += (_, _) => publishSize();'))

  # hardware characters + backspace timing
  $raw = Rep $raw (& $L @(
'        core.KeyDown += (_, e) =>',
'        {',
'            // Auto-repeat is generated by the framework itself.')) (& $L @(
'        core.CharacterReceived += (_, e) =>',
'        {',
'            if (charLogs++ < 10) log($"char {e.KeyCode:X} editFocused {editFocused}");',
'',
'            // While the edit context has focus it delivers the text (hardware keys included), so this would double it.',
'            if (!editFocused)',
'                bridge.PostChar((char)e.KeyCode);',
'        };',
'',
'        core.KeyDown += (_, e) =>',
'        {',
'            if (e.VirtualKey == VirtualKey.Back)',
'                lastBackspaceTicks = Environment.TickCount64;',
'',
'            // Auto-repeat is generated by the framework itself.'))

  # size publishing: round instead of truncating, log changes
  $raw = Rep $raw (& $L @(
'        bridge.SetSize((int)(Panel.ActualWidth * scale), (int)(Panel.ActualHeight * scale), dpi);')) (& $L @(
'        int width = (int)Math.Round(Panel.ActualWidth * scale);',
'        int height = (int)Math.Round(Panel.ActualHeight * scale);',
'',
'        string now = $"{width}x{height} dpi {dpi}";',
'',
'        if (now != lastPublishedSize)',
'        {',
'            lastPublishedSize = now;',
'            log($"size {now}");',
'        }',
'',
'        bridge.SetSize(width, height, dpi);'))

  # bridge wiring
  $raw = Rep $raw '            bridge.StoragePath = Path.Combine(ApplicationData.Current.LocalFolder.Path, "osu-framework");' (& $L @(
'            bridge.StoragePath = Path.Combine(ApplicationData.Current.LocalFolder.Path, "osu-framework");',
'            bridge.SetTextInputActive = setTextInput;',
'            bridge.LaunchUri = launchUri;'))

  # members
  $members = & $L @(
'    private int charLogs;',
'    private int textLogs;',
'    private string lastPublishedSize = "";',
'    private long lastBackspaceTicks;',
'',
'    private CoreTextEditContext? editContext;',
'    private bool editFocused;',
'    private string shadow = "";',
'    private CoreTextRange selection;',
'',
'    // Blank text in front of the caret, so the keyboard always has something to delete with backspace.',
'    private const int shadow_padding = 64;',
'',
'    private bool launchUri(string url)',
'    {',
'        if (!Uri.TryCreate(url, UriKind.Absolute, out var uri))',
'            return false;',
'',
'        _ = Dispatcher.RunAsync(CoreDispatcherPriority.Normal, async () =>',
'        {',
'            try',
'            {',
'                bool ok = await Launcher.LaunchUriAsync(uri);',
'                log($"launch {url}: {ok}");',
'            }',
'            catch (Exception e)',
'            {',
'                log("launch failed: " + e.Message);',
'            }',
'        });',
'',
'        return true;',
'    }',
'',
'    // Called from a framework thread; everything touching the edit context or the input pane happens on the UI thread.',
'    private void setTextInput(bool active)',
'    {',
'        _ = Dispatcher.RunAsync(CoreDispatcherPriority.Normal, () =>',
'        {',
'            try',
'            {',
'                if (active == editFocused)',
'                    return;',
'',
'                editContext ??= createEditContext();',
'',
'                if (active)',
'                {',
'                    shadow = new string('' '', shadow_padding);',
'                    selection = new CoreTextRange { StartCaretPosition = shadow.Length, EndCaretPosition = shadow.Length };',
'                    editContext.NotifyFocusEnter();',
'                    InputPane.GetForCurrentView().TryShow();',
'                }',
'                else',
'                {',
'                    editContext.NotifyFocusLeave();',
'                    InputPane.GetForCurrentView().TryHide();',
'                }',
'',
'                editFocused = active;',
'                log($"text input {(active ? "on" : "off")}");',
'            }',
'            catch (Exception e)',
'            {',
'                log("text input toggle failed: " + e);',
'            }',
'        });',
'    }',
'',
'    private CoreTextEditContext createEditContext()',
'    {',
'        var context = CoreTextServicesManager.GetForCurrentView().CreateEditContext();',
'        context.InputScope = CoreTextInputScope.Default;',
'        context.InputPaneDisplayPolicy = CoreTextInputPaneDisplayPolicy.Manual;',
'',
'        context.TextRequested += (_, e) =>',
'        {',
'            int start = Math.Clamp(e.Request.Range.StartCaretPosition, 0, shadow.Length);',
'            int end = Math.Clamp(e.Request.Range.EndCaretPosition, start, shadow.Length);',
'            e.Request.Text = shadow.Substring(start, end - start);',
'        };',
'',
'        context.SelectionRequested += (_, e) => e.Request.Selection = selection;',
'',
'        context.SelectionUpdating += (_, e) =>',
'        {',
'            selection = e.Selection;',
'            e.Result = CoreTextSelectionUpdatingResult.Succeeded;',
'        };',
'',
'        context.TextUpdating += (_, e) =>',
'        {',
'            int start = Math.Clamp(e.Range.StartCaretPosition, 0, shadow.Length);',
'            int end = Math.Clamp(e.Range.EndCaretPosition, start, shadow.Length);',
'            int removed = end - start;',
'',
'            shadow = shadow.Remove(start, removed).Insert(start, e.Text);',
'            selection = e.NewSelection;',
'',
'            // A hardware backspace also arrives as a key event, which the framework already handles.',
'            bool hardwareBackspace = e.Text.Length == 0 && Environment.TickCount64 - lastBackspaceTicks < 250;',
'',
'            if (!hardwareBackspace)',
'            {',
'                for (int i = 0; i < removed; i++)',
'                {',
'                    bridge.PostKey((int)VirtualKey.Back, true);',
'                    bridge.PostKey((int)VirtualKey.Back, false);',
'                }',
'            }',
'',
'            bridge.PostText(e.Text);',
'            e.Result = CoreTextTextUpdatingResult.Succeeded;',
'',
'            if (textLogs++ < 30) log($"text updating {start}-{end} \"{e.Text}\" removed {removed} hardwareBackspace {hardwareBackspace}");',
'        };',
'',
'        // The system took focus away (e.g. the keyboard was dismissed with B). The framework still thinks text input is on.',
'        context.FocusRemoved += (_, _) =>',
'        {',
'            editFocused = false;',
'            log("text input focus removed by the system");',
'        };',
'',
'        return context;',
'    }',
'',
'    private void log(string line)')
  $raw = Rep $raw '    private void log(string line)' $members
  $raw
}

