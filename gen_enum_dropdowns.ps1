# Generates uwp-osu\XboxEnumDropdowns.cs: one RegisterEnumDropdown<T>() per public enum used as Bindable<T> on a [SettingSource] property.
param([string]$Src = 'D:\osu-xbox-scratch\osu-aot', [string]$Out = 'D:\osu-xbox-scratch\uwp-osu\XboxEnumDropdowns.cs')
$prims = 'bool','int','float','double','string','Color4','long','uint','byte','int?','double?','float?'
$files = Get-ChildItem $Src -Recurse -Filter *.cs | Where-Object { $_.FullName -notmatch '\\Tests\\|\\obj\\|\\bin\\|\\osu\.Game\.Tests|\\osu\.Game\.Tournament|\\osu\.Desktop' }

# 1. candidate simple names from [SettingSource] properties
$cand = New-Object System.Collections.Generic.HashSet[string]
foreach ($f in $files) {
    $t = [IO.File]::ReadAllText($f.FullName)
    if ($t -notmatch 'SettingSource\(') { continue }
    $rx = '\[SettingSource\((?:(?!\]\s*(?:public|protected|internal|private)).)*?\]\s*(?:\[[^\]]*\]\s*)*(?:public|protected|internal)\s+(?:virtual\s+|abstract\s+|override\s+)?(?:Bindable|BindableNumber)<([^>]+)>'
    foreach ($m in [regex]::Matches($t, $rx, 'Singleline')) {
        $a = $m.Groups[1].Value.Trim()
        if ($prims -contains $a) { continue }
        [void]$cand.Add(($a -split '\.')[-1])
    }
}
"candidates: $($cand -join ', ')"

# 2. resolve each name to public enum declarations with a fully qualified name
$typeRx = '^(\s*)(?:\[[^\]]*\]\s*)*((?:(?:public|internal|private|protected|static|sealed|abstract|partial|unsafe|readonly|file)\s+)*)(class|struct|interface|record)\s+(\w+)(<[^>]*>)?'
$found = [ordered]@{}
foreach ($f in $files) {
    $t = [IO.File]::ReadAllText($f.FullName)
    if ($t -notmatch '\benum\s+(' + ($cand -join '|') + ')\b') { continue }
    $lines = $t -split "`r?`n"
    $ns = ($lines | Select-String -Pattern '^\s*namespace\s+([\w.]+)' | Select-Object -First 1).Matches.Groups[1].Value
    for ($i = 0; $i -lt $lines.Count; $i++) {
        $m = [regex]::Match($lines[$i], '^(\s*)public\s+enum\s+(\w+)')
        if (-not $m.Success -or -not $cand.Contains($m.Groups[2].Value)) { continue }
        $name = $m.Groups[2].Value; $indent = $m.Groups[1].Value.Length; $chain = @(); $ok = $true
        for ($j = $i - 1; $j -ge 0 -and $indent -gt 0; $j--) {
            $tm = [regex]::Match($lines[$j], $typeRx)
            if ($tm.Success -and $tm.Groups[1].Value.Length -lt $indent) {
                if ($tm.Groups[2].Value -notmatch 'public' -or $tm.Groups[5].Success -and $tm.Groups[5].Value) { $ok = $false; break }
                $chain = , $tm.Groups[4].Value + $chain; $indent = $tm.Groups[1].Value.Length
            }
        }
        # namespace-level indentation (block namespace) leaves $indent > 0 with an empty chain: fine
        if (-not $ok -or -not $ns) { Write-Warning "skipped $name in $($f.Name) (non-public or generic container)"; continue }
        $full = "global::$ns." + (($chain + $name) -join '.')
        $found[$full] = $f.Name
    }
}
# enums that live in osu.Framework (Drawable.cs), outside the scanned osu source tree
foreach ($e in 'osu.Framework.Graphics.Direction', 'osu.Framework.Graphics.RotationDirection') { $found["global::$e"] = 'osu.Framework' }
$found.GetEnumerator() | ForEach-Object { "  $($_.Key)   [$($_.Value)]" }
$missing = $cand | Where-Object { $n = $_; -not ($found.Keys | Where-Object { $_ -like "*.$n" -or $_ -like "*$n" }) }
if ($missing) { Write-Warning "no public enum found for: $($missing -join ', ')" }

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('// <auto-generated> by gen_enum_dropdowns.ps1 </auto-generated>')
[void]$sb.AppendLine('namespace UwpOsu')
[void]$sb.AppendLine('{')
[void]$sb.AppendLine('    /// <summary>Native AOT cannot build ModSettingsEnumDropdown<T> for enum types at runtime; instantiate each statically.</summary>')
[void]$sb.AppendLine('    internal static class XboxEnumDropdowns')
[void]$sb.AppendLine('    {')
[void]$sb.AppendLine('        public static void Register()')
[void]$sb.AppendLine('        {')
foreach ($k in $found.Keys) { [void]$sb.AppendLine("            osu.Game.Configuration.SettingSourceExtensions.RegisterEnumDropdown<$k>();") }
[void]$sb.AppendLine('        }')
[void]$sb.AppendLine('    }')
[void]$sb.AppendLine('}')
[IO.File]::WriteAllText($Out, $sb.ToString())
"wrote $Out ($($found.Count) enums)"
