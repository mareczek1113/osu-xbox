using System;
using System.IO;
using System.Threading;
using osu.Framework;
using osu.Framework.Platform;
using osu.Framework.Platform.Xbox;
using Windows.Gaming.Input;
using Windows.Graphics.Display;
using Windows.Storage;
using Windows.System;
using Windows.UI.Core;
using Windows.UI.Input;
using Windows.UI.ViewManagement;
using Windows.UI.Xaml;
using Windows.UI.Xaml.Controls;
using Windows.UI.Xaml.Input;

namespace UwpOsu;

public sealed partial class MainPage : Page
{
    private readonly UwpHostBridge bridge = new UwpHostBridge();
    private readonly string statusPath = Path.Combine(ApplicationData.Current.LocalFolder.Path, "status.txt");
    private bool started;
    private int pointerLogs;
    private int pressLogs;
    private long panelMoves, panelPresses, coreMoves, corePresses, panelStamp, keyCount, moveStamp;
    private double rawX, rawY;
    private System.Threading.Timer? watchdog;

    public MainPage()
    {
        InitializeComponent();

        File.WriteAllText(statusPath, "page created\n");
        bridge.PadPointerEnabled = App.PointerMode != "system";
        File.AppendAllText(statusPath, $"pointer mode: {App.PointerMode}\n");
        bridge.PadPointerMoved += (x, y) => { rawX = x; rawY = y; moveStamp = Environment.TickCount64; };

        Loaded += (_, _) => start();
        Panel.SizeChanged += (_, _) => publishSize();

        // The scale can change without the panel resizing (display scale setting, moving between displays), and positions depend on it.
        DisplayInformation.GetForCurrentView().DpiChanged += (_, _) => publishSize();

        Window.Current.CoreWindow.Activated += (_, e) => bridge.SetActive(e.WindowActivationState != CoreWindowActivationState.Deactivated);
        Windows.UI.Xaml.Application.Current.Suspending += (_, _) => bridge.NotifySuspending();
        Windows.UI.Xaml.Application.Current.Resuming += (_, _) => bridge.NotifyResumed();

        wireInput();
    }

    private void wireInput()
    {
        var core = Window.Current.CoreWindow;

        // B is the system "back" on Xbox and closes the app unless the request is handled. The framework reads B straight from the pad,
        // so osu! still sees the press and decides what back means (leaving the app is then only possible through the Guide button).
        try { SystemNavigationManager.GetForCurrentView().BackRequested += (_, e) => e.Handled = true; } catch (Exception ex) { log("back handler failed: " + ex.Message); }

        core.KeyDown += (_, e) =>
        {
            // Auto-repeat is generated by the framework itself.
            keyCount++;
            if (!e.KeyStatus.WasKeyDown)
                bridge.PostKey(resolveKey(e), true);
        };
        core.KeyUp += (_, e) => bridge.PostKey(resolveKey(e), false);

        Panel.PointerMoved += (_, e) =>
        {
            var p = e.GetCurrentPoint(Panel).Position;
            panelMoves++;
            if (App.PointerMode == "hybrid") return; // hybrid: the pad drives the cursor; the console's stick-driven system pointer must not move it
            panelStamp = Environment.TickCount64;
            moveStamp = panelStamp;
            rawX = p.X;
            rawY = p.Y;
            if (pointerLogs++ < 3) log($"ui pointer moved {p} device {e.Pointer.PointerDeviceType}");
            bridge.PostPointerMove((float)p.X, (float)p.Y);
        };

        Panel.PointerPressed += (_, e) => { panelPresses++; panelStamp = Environment.TickCount64; logPress("panel", e.Pointer.PointerDeviceType.ToString(), e.GetCurrentPoint(Panel).Properties.PointerUpdateKind); var pt = e.GetCurrentPoint(Panel); postButton(pt.Position, pt.Properties.PointerUpdateKind, true); };
        Panel.PointerReleased += (_, e) => { var pt = e.GetCurrentPoint(Panel); postButton(pt.Position, pt.Properties.PointerUpdateKind, false); };

        // A physical USB mouse is not supported: Xbox only delivers hardware mouse input to UWP apps Microsoft has allowed individually.
        // (The console turns the left stick into mouse-like events, so no mouse code runs here at all; the pad handler drives the cursor.)
        var coreWin = Window.Current.CoreWindow;

        // Hiding the system pointer (PointerCursor = null) stops its move events on Xbox (build 16: moves 0) but presses (A) still arrive,
        // so in "hybrid" mode the pad handler drives the osu! cursor and the console pointer is only used for clicks.
        // The console re-shows its pointer when something resets the window cursor (focus changes, the swap chain being replaced,
        // the first pointer event after launch), so the cursor is hidden again on every such event, not just once at startup.
        int cursorResets = 0;
        void hideSystemPointer()
        {
            if (App.PointerMode != "hybrid") return;
            try
            {
                var cw = Window.Current.CoreWindow;
                if (cw.PointerCursor != null)
                {
                    cw.PointerCursor = null;
                    if (++cursorResets <= 20) log("system pointer was visible, hidden again (" + cursorResets + ")");
                }
            }
            catch (Exception ex) { log("hide system pointer failed: " + ex.Message); }
        }
        hideSystemPointer();
        Loaded += (_, _) => hideSystemPointer();
        Window.Current.Activated += (_, _) => hideSystemPointer();
        Window.Current.VisibilityChanged += (_, _) => hideSystemPointer();
        coreWin.PointerEntered += (_, _) => hideSystemPointer();
        coreWin.PointerMoved += (_, e) =>
        {
            hideSystemPointer();
            coreMoves++;
            if (App.PointerMode == "hybrid") return; // see Panel.PointerMoved
            moveStamp = Environment.TickCount64;
            rawX = e.CurrentPoint.Position.X;
            rawY = e.CurrentPoint.Position.Y;
            if (Environment.TickCount64 - panelStamp < 500) return;
            var pt = e.CurrentPoint;
            bridge.PostPointerMove((float)pt.Position.X, (float)pt.Position.Y);
        };
        coreWin.PointerPressed += (_, e) =>
        {
            corePresses++;
            var pt = e.CurrentPoint;
            logPress("core", pt.PointerDevice.PointerDeviceType.ToString(), pt.Properties.PointerUpdateKind);
            if (Environment.TickCount64 - panelStamp < 500) return;
            postButton(pt.Position, pt.Properties.PointerUpdateKind, true);
        };
        coreWin.PointerReleased += (_, e) =>
        {
            if (Environment.TickCount64 - panelStamp < 500) return;
            var pt = e.CurrentPoint;
            postButton(pt.Position, pt.Properties.PointerUpdateKind, false);
        };

        Panel.PointerWheelChanged += (_, e) =>
        {
            var props = e.GetCurrentPoint(Panel).Properties;
            float notches = props.MouseWheelDelta / 120f;

            if (props.IsHorizontalMouseWheel)
                bridge.PostPointerWheel(notches, 0, true);
            else
                bridge.PostPointerWheel(0, notches, true);
        };

        wireText();

        bridge.LaunchUri = url =>
        {
            if (!Uri.TryCreate(url, UriKind.Absolute, out var uri))
                return false;

            // Launcher must be called on the UI thread. This is fire and forget: the framework only needs to know the request was made.
            _ = Dispatcher.RunAsync(CoreDispatcherPriority.Normal, async () =>
            {
                try
                {
                    await Windows.System.Launcher.LaunchUriAsync(uri);
                }
                catch (Exception e)
                {
                    log("launch uri failed: " + e.Message);
                }
            });

            return true;
        };

        // Gamepad.GetCurrentReading is safe to call from any thread, so the framework polls it directly.
        bridge.PollGamepad = () =>
        {
            var pads = Gamepad.Gamepads;
            if (pads.Count == 0) return null;

            var r = pads[0].GetCurrentReading();

            bool view = (r.Buttons & GamepadButtons.View) != 0;
            if (view && !lastView && textActive)
                _ = Dispatcher.RunAsync(CoreDispatcherPriority.Normal, showKeyboard);
            lastView = view;
            return new UwpGamepadReading((UwpGamepadButtons)(uint)r.Buttons,
                (float)r.LeftThumbstickX, (float)r.LeftThumbstickY,
                (float)r.RightThumbstickX, (float)r.RightThumbstickY,
                (float)r.LeftTrigger, (float)r.RightTrigger);
        };
    }

    private bool textActive;
    private bool clearingSink;

    // Text arrives through a hidden, always-empty TextBox. Focusing it is what makes the Xbox bring up the on-screen keyboard, and it also
    // receives hardware typing. Because the box is emptied after every change, a Backspace in it never has anything to delete,
    // so the delete only happens once, through the key event the framework handles.
    private void wireText()
    {
        bridge.SetTextInputActive = active => _ = Dispatcher.RunAsync(CoreDispatcherPriority.Normal, () => setTextActive(active));

        TextSink.TextChanged += (_, _) =>
        {
            if (clearingSink || TextSink.Text.Length == 0)
                return;

            string text = TextSink.Text;

            clearingSink = true;
            TextSink.Text = string.Empty;
            clearingSink = false;

            bridge.PostText(text);
        };

        // Fallback for when the box could not take focus: characters then arrive here instead.
        Window.Current.CoreWindow.CharacterReceived += (_, e) =>
        {
            if (textActive && FocusManager.GetFocusedElement() != TextSink)
                bridge.PostChar((char)e.KeyCode);
        };
    }

    private bool lastView;

    private void showKeyboard()
    {
        try
        {
            TextSink.Focus(FocusState.Programmatic);
            InputPane.GetForCurrentView().TryShow();
        }
        catch (Exception e)
        {
            log("show keyboard failed: " + e.Message);
        }
    }

    private void setTextActive(bool active)
    {
        // Can be called repeatedly for the same session.
        if (active == textActive && (!active || FocusManager.GetFocusedElement() == TextSink))
            return;

        textActive = active;

        try
        {
            if (active)
            {
                // Do not focus the hidden box here: that makes the console pop up the on-screen keyboard every time osu! focuses a text box
                // (e.g. the song select search box when a map is clicked). Hardware typing still arrives through CharacterReceived;
                // the on-screen keyboard is opened on request with the View button (see showKeyboard).
            }
            else
            {
                InputPane.GetForCurrentView().TryHide();
                Focus(FocusState.Programmatic);
            }
        }
        catch (Exception e)
        {
            log("text input toggle failed: " + e.Message);
        }
    }

    // CoreWindow reports generic Shift/Control/Menu; use the scan code / extended flag to tell left from right.
    private static int resolveKey(KeyEventArgs e)
    {
        int vk = (int)e.VirtualKey;

        return vk switch
        {
            16 => e.KeyStatus.ScanCode == 54 ? 161 : 160,
            17 => e.KeyStatus.IsExtendedKey ? 163 : 162,
            18 => e.KeyStatus.IsExtendedKey ? 165 : 164,
            _ => vk
        };
    }

    private void logPress(string source, string device, PointerUpdateKind kind)
    {
        if (pressLogs++ < 20)
            log($"pointer press via {source}: device {device}, kind {kind}");
    }

    private void postButton(Windows.Foundation.Point pos, PointerUpdateKind kind, bool pressed)
    {
        // Make sure the framework knows where the pointer is before the button changes (e.g. touch or a pointer that jumped).
        // In hybrid mode the console pointer is hidden and stays put, so its press position is stale (A and the mouse buttons come through it).
        // The pad / raw mouse already placed the osu! cursor; moving it to the stale position is what made it snap back on every click.
        if (App.PointerMode != "hybrid")
            bridge.PostPointerMove((float)pos.X, (float)pos.Y);

        switch (kind)
        {
            case PointerUpdateKind.LeftButtonPressed:
            case PointerUpdateKind.LeftButtonReleased:
                bridge.PostPointerButton(0, pressed);
                break;

            case PointerUpdateKind.MiddleButtonPressed:
            case PointerUpdateKind.MiddleButtonReleased:
                bridge.PostPointerButton(1, pressed);
                break;

            case PointerUpdateKind.RightButtonPressed:
            case PointerUpdateKind.RightButtonReleased:
                bridge.PostPointerButton(2, pressed);
                break;

            case PointerUpdateKind.XButton1Pressed:
            case PointerUpdateKind.XButton1Released:
                bridge.PostPointerButton(3, pressed);
                break;

            case PointerUpdateKind.XButton2Pressed:
            case PointerUpdateKind.XButton2Released:
                bridge.PostPointerButton(4, pressed);
                break;
        }
    }

    private void log(string line)
    {
        try
        {
            File.AppendAllText(statusPath, $"{DateTime.Now:HH:mm:ss.fff} {line}\n");
        }
        catch
        {
        }
    }

    private static long mb(ulong bytes) => (long)(bytes / (1024 * 1024));

    private void logMemory(string when)
    {
        try
        {
            log($"memory ({when}): usage {mb(MemoryManager.AppMemoryUsage)} MB, limit {mb(MemoryManager.AppMemoryUsageLimit)} MB, " +
                $"expected limit {mb(MemoryManager.ExpectedAppMemoryUsageLimit)} MB, level {MemoryManager.AppMemoryUsageLevel}");
        }
        catch (Exception e)
        {
            log("memory query failed: " + e.Message);
        }
    }

    private void publishSize()
    {
        float dpi = DisplayInformation.GetForCurrentView().LogicalDpi;
        float scale = dpi / 96f;
        bridge.SetSize((int)(Panel.ActualWidth * scale), (int)(Panel.ActualHeight * scale), dpi);
    }

    private void start()
    {
        if (started) return;
        started = true;

        Veldrid.D3D11.UwpDiagnostics.Log = log;

        try
        {
            publishSize();

            // The raw mouse position starts in the middle, like the pad cursor, so the first mouse movement does not jump to a corner.
            rawX = Panel.ActualWidth / 2;
            rawY = Panel.ActualHeight / 2;

            var dispatcher = Dispatcher;
            bridge.RunOnUiThread = action =>
            {
                if (dispatcher.HasThreadAccess)
                {
                    action();
                    return;
                }

                using var done = new ManualResetEventSlim();
                Exception? error = null;

                _ = dispatcher.RunAsync(CoreDispatcherPriority.Normal, () =>
                {
                    try
                    {
                        action();
                    }
                    catch (Exception e)
                    {
                        error = e;
                    }
                    finally
                    {
                        done.Set();
                    }
                });

                done.Wait();
                if (error != null) throw error;
            };
            bridge.SwapChainPanelPointer = WinRT.MarshalInspectable<SwapChainPanel>.FromManaged(Panel);
            bridge.StoragePath = Path.Combine(ApplicationData.Current.LocalFolder.Path, "osu-framework");
            log($"panel ready {bridge.PixelSize} dpi {bridge.LogicalDpi}");
            logMemory("startup");

            // The limit decides what is possible (1 GB for apps vs 5 GB for games), so keep watching it while the app runs.
            MemoryManager.AppMemoryUsageLimitChanging += (_, e) => log($"memory: limit changing {mb(e.OldLimit)} -> {mb(e.NewLimit)} MB");
            var memoryTimer = new DispatcherTimer { Interval = TimeSpan.FromSeconds(10) };
            memoryTimer.Tick += (_, _) =>
        {
            logMemory("tick");
            log($"input counts: panel moves {panelMoves}, panel presses {panelPresses}, core moves {coreMoves}, core presses {corePresses}, keys {keyCount}");
            log($"gc: gen0 {GC.CollectionCount(0)}, gen1 {GC.CollectionCount(1)}, gen2 {GC.CollectionCount(2)}, total pause {GC.GetTotalPauseDuration().TotalMilliseconds:0} ms, heap {mb((ulong)GC.GetTotalMemory(false))} MB");
        };
            memoryTimer.Start();

            // Fewer, shorter blocking collections: gen2 pauses on a big heap are a likely cause of rare freezes.
            try { System.Runtime.GCSettings.LatencyMode = System.Runtime.GCLatencyMode.SustainedLowLatency; }
            catch (Exception ex) { log("gc latency mode failed: " + ex.Message); }

            // Hang watchdog on a thread-pool thread (independent of the UI and game threads): logs when no frame was presented for a while.
            long lastReported = 0;
            watchdog = new System.Threading.Timer(_ =>
            {
                long last = Volatile.Read(ref Veldrid.D3D11.UwpDiagnostics.LastPresentTick);
                if (last == 0) return;

                long gap = Environment.TickCount64 - last;
                if (gap > 700 && last != lastReported)
                {
                    lastReported = last;
                    log($"stall: no frame presented for {gap} ms (gc gen2 {GC.CollectionCount(2)}, pause {GC.GetTotalPauseDuration().TotalMilliseconds:0} ms)");
                }
            }, null, 500, 500);
        }
        catch (Exception e)
        {
            log("setup failed: " + e);
            return;
        }

        var thread = new Thread(() =>
        {
            try
            {
                log("host starting");

                using var host = Host.GetUwpHost(bridge, "osu");
                host.Run(new XboxOsuGame(log));

                log("host exited normally");
            }
            catch (Exception e)
            {
                log("host crashed: " + e);
            }
        }) { Name = "Framework host", IsBackground = true };

        thread.Start();
    }
}
